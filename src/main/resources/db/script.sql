-- ============================================================
-- Script de base de datos: user-service (Sistema de Foros)
-- Base de datos: Oracle Autonomous Database (BDFullstack3)
-- Las contraseñas se guardan cifradas con BCrypt:
--   usuarios ADMIN   -> Admin1234
--   usuarios USUARIO -> Usuario1234
-- ============================================================

DROP TABLE USUARIOS CASCADE CONSTRAINTS;

CREATE TABLE USUARIOS (
    ID             NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME       VARCHAR2(30 CHAR)  NOT NULL UNIQUE,
    EMAIL          VARCHAR2(150 CHAR) NOT NULL UNIQUE,
    PASSWORD       VARCHAR2(100 CHAR) NOT NULL,
    NOMBRE         VARCHAR2(100 CHAR) NOT NULL,
    ROL            VARCHAR2(20 CHAR)  NOT NULL CHECK (ROL IN ('USUARIO', 'ADMIN')),
    FECHA_REGISTRO TIMESTAMP(9)       NOT NULL
);

